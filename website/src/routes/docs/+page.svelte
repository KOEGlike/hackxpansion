<h1>HackXPansion documentation</h1>

<h2>What is this all about?</h2>
<p>
	HackXPansion is an event run by Hack Club, a global community of high school hackers. Make four
	expansion cards, write drivers for them, get funding, and earn a custom console to use them in.
</p>

<h2>Where do I get started?</h2>
<p>
	<a href="https://slack.hackclub.com/">Join the Hack Club Slack</a> and visit the
	<a href="https://hackclub.enterprise.slack.com/archives/C0A9B4152BY">#hackxpansion</a>
	channel. The community can help while you work through the getting-started guides.
</p>
<p>
	You will need to track your time with journals, time lapses, or streams. This evidence is required
	for the console reward and helps document your work.
</p>

<h2>What if I am new to hardware?</h2>
<p>
	The guides and resources are designed to help you make your first module or even your first PCB.
</p>

<h2>How powerful will the console be?</h2>
<p>
	The console uses an RP2354B MCU as its main processor, from the next generation of the chip used
	in
	<a href="https://sprig.hackclub.com/">Sprig</a>. It is capable enough for many projects, and you
	can add a coprocessor when you need more power.
</p>

<h3>What is this all about?</h3>
This is an event run by Hack Club, a global community of high school hackers.
<br />
The goal of this event is to make 4 expansion cards, write drivers for them, get funding, and then get
a custom console to use them in. And maybe even get other people's modules.

<h3>Where do I get started?</h3>
<a href="https://slack.hackclub.com/">Join</a> the Hack Club Slack and check out the
<a href="https://hackclub.enterprise.slack.com/archives/C0A9B4152BY">#hackxpansion</a> channel. We
have a bunch of people who are eager to help! Also check out our getting started guides and
tutorials to learn more about making your first expansion card and programming drivers/apps.
<br />
You will need to track your time by writing a journal/making a time-lapse/streaming your work. This is
a requirement to get the free console at the end, and it's also a great way to get started with electronics.

<h3>But I'm a beginner and don't know hardware</h3>
No problem! We have guides and resources that will help you make your first module, even your first PCB

<h3>How powerful will the console be?</h3>
The console will use a RP2354B MCU as it's main processor, it is the next generation of the chip used
in
<a href="https://sprig.hackclub.com/">Sprig</a>. It can handle a lot of stuff, and it's really easy
to program for. You could make a co-processor if you yearned for more power!!
